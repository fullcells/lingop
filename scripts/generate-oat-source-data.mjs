import fs from "node:fs";
import path from "node:path";
import { createJiti } from "jiti";

const projectRoot = process.cwd();
// This scope must not overlap a consumer's path scopes. OAT generation then
// applies Lingop-owned strings to every GUI/focus language in that consumer's
// config, including strings used only inside packaged UI components.
const lingopPackageScope = "__lingop_package__";
const jiti = createJiti(import.meta.url);
const {
  extractOATCalleeStringsFromFile,
  getAllOATSourceFiles,
} = await jiti.import(
  path.join(projectRoot, "src/oat/build/source-extractor.ts"),
);

const sourceFiles = getAllOATSourceFiles([path.join(projectRoot, "src")])
  .filter((file) => !/\.test\.[jt]sx?$/.test(file))
  .filter((file) => !file.endsWith("lingop-source-data.generated.ts"));

function collectTexts(calleeName) {
  return [...new Set(
    sourceFiles.flatMap((file) =>
      extractOATCalleeStringsFromFile(file, calleeName),
    ),
  )].sort((a, b) => a.localeCompare(b));
}

function textsByGlobalScope(texts) {
  return texts.length > 0 ? { [lingopPackageScope]: texts } : {};
}

const sourceData = {
  guiTextsByScope: textsByGlobalScope(collectTexts("OAT")),
  focusTextsByScope: textsByGlobalScope(collectTexts("OAT2")),
  staticFocusTextsByScope: textsByGlobalScope(
    collectTexts("getStaticFocusLangAText"),
  ),
};

const output = `// Generated by npm run generate:oat-source-data. Do not edit directly.\n\nimport type { OATSourceData } from "./types.js";\n\nexport const lingopOATSourceData: OATSourceData = ${JSON.stringify(sourceData, null, 2)};\n`;

fs.writeFileSync(
  path.join(projectRoot, "src/oat/lingop-source-data.generated.ts"),
  output,
);
